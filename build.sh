#!/usr/bin/env bash
set -euo pipefail

CALLER_DIR=$PWD
SCRIPT_DIR=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)
cd -- "$SCRIPT_DIR"

usage() {
  cat <<'EOF'
Usage: ./build.sh [--iso | --update | --both] [update options]

  --iso       Build the complete bootable ISO (the default).
  --update    Build a signed .aup package from two existing root trees.
  --both      Build the ISO, then make a signed .aup from --base-root to the
              root tree produced by that ISO build.

Update options:
  --base-root DIR       Existing arkanaOS release root tree
  --target-root DIR     Target root tree (accepted with --update only)
  --signing-key FILE    Private arkup signing key
  --public-key FILE     Matching arkup verification key
  --output-dir DIR      Update output directory
  --architecture NAME  Package architecture (default: x86_64)
  --description TEXT    Optional package description

Examples:
  ./build.sh --iso
  ./build.sh --update --base-root old-root --target-root new-root \
    --signing-key release.key --public-key release.pub
  ./build.sh --both --base-root old-root \
    --signing-key release.key --public-key release.pub

The signing key is mounted read-only into the bounded update-builder container.
Keep it private and outside the repository.
EOF
}

MODE=iso
if (($#)); then
  case "$1" in
    --iso) MODE=iso; shift ;;
    --update) MODE=update; shift ;;
    --both) MODE=both; shift ;;
    -h|--help) usage; exit 0 ;;
    *) echo "Unknown build mode: $1" >&2; usage >&2; exit 2 ;;
  esac
fi

if [[ "$MODE" == update ]]; then
  UPDATE_ARGS=()
  while (($#)); do
    case "$1" in
      --base-root|--target-root|--signing-key|--public-key|--output-dir|--architecture|--description)
        option=$1
        if (($# < 2)) || [[ -z "$2" ]]; then
          echo "Missing value for $option" >&2
          exit 2
        fi
        value=$2
        case "$option" in
          --base-root|--target-root|--signing-key|--public-key|--output-dir)
            if [[ "$value" != /* ]]; then value="$CALLER_DIR/$value"; fi
            ;;
        esac
        UPDATE_ARGS+=("$option" "$value")
        shift 2
        ;;
      *) UPDATE_ARGS+=("$1"); shift ;;
    esac
  done
  exec "$SCRIPT_DIR/build-update.sh" "${UPDATE_ARGS[@]}"
fi

UPDATE_ARGS=()
if [[ "$MODE" == both ]]; then
  BASE_ROOT=
  SIGNING_KEY=
  PUBLIC_KEY=
  while (($#)); do
    case "$1" in
      --base-root|--signing-key|--public-key|--output-dir|--architecture|--description)
        option=$1
        if (($# < 2)) || [[ -z "$2" || "$2" == --* ]]; then
          echo "Missing value for $option" >&2
          usage >&2
          exit 2
        fi
        value=$2
        case "$option" in
          --base-root|--signing-key|--public-key|--output-dir)
            if [[ "$value" != /* ]]; then value="$CALLER_DIR/$value"; fi
            case "$option" in
              --base-root) BASE_ROOT=$value ;;
              --signing-key) SIGNING_KEY=$value ;;
              --public-key) PUBLIC_KEY=$value ;;
            esac
            ;;
        esac
        UPDATE_ARGS+=("$option" "$value")
        shift 2
        ;;
      --target-root)
        echo "--target-root is generated by --both; use --update to select a target tree." >&2
        exit 2
        ;;
      -h|--help)
        usage
        exit 0
        ;;
      *)
        echo "Unknown update option for --both: $1" >&2
        usage >&2
        exit 2
        ;;
    esac
  done

  for name in BASE_ROOT SIGNING_KEY PUBLIC_KEY; do
    if [[ -z "${!name}" ]]; then
      option_name=${name,,}
      option_name=${option_name//_/-}
      echo "--both requires --$option_name" >&2
      usage >&2
      exit 2
    fi
  done
  if [[ ! -d "$BASE_ROOT" ]]; then
    echo "Base root is not a directory: $BASE_ROOT" >&2
    exit 2
  fi
  if [[ ! -f "$SIGNING_KEY" || ! -f "$PUBLIC_KEY" ]]; then
    echo "Signing and public keys must be existing regular files." >&2
    exit 2
  fi
elif (($#)); then
  echo "--iso does not accept additional arguments." >&2
  usage >&2
  exit 2
fi

ARKANA_RELEASE_PREFIX=${ARKANA_RELEASE_PREFIX:-r1-a1}
mkdir -p output src staging

# Keep builds resource-bounded by default; ARKANA_BUILD_* variables tune the limits.
HOST_CPUS=$(nproc)
DEFAULT_CPUS=2
if [ "$HOST_CPUS" -lt "$DEFAULT_CPUS" ]; then
  DEFAULT_CPUS=$HOST_CPUS
fi
CPUS=${ARKANA_BUILD_CPUS:-$DEFAULT_CPUS}
if ! [[ "$CPUS" =~ ^[0-9]+$ ]] || [ "$CPUS" -lt 1 ] || [ "$CPUS" -gt "$HOST_CPUS" ]; then
  echo "ARKANA_BUILD_CPUS must be between 1 and $HOST_CPUS." >&2
  exit 1
fi
AVAILABLE_RAM_MB=$(awk '/MemAvailable/ {print int($2/1024)}' /proc/meminfo)
AVAILABLE_SWAP_MB=$(awk '/SwapFree/ {print int($2/1024)}' /proc/meminfo)

echo "The system reports $HOST_CPUS CPUs, $AVAILABLE_RAM_MB MiB of available RAM, and $AVAILABLE_SWAP_MB MiB of free swap."

if [ "$AVAILABLE_RAM_MB" -lt 2048 ]; then
  echo "At least 2048 MiB of available RAM is required to start the build safely." >&2
  exit 1
fi
DEFAULT_RAM_MB=$(( AVAILABLE_RAM_MB * 60 / 100 ))
if [ "$DEFAULT_RAM_MB" -gt 4096 ]; then
  DEFAULT_RAM_MB=4096
fi
CONTAINER_RAM_MB=${ARKANA_BUILD_RAM_MB:-$DEFAULT_RAM_MB}
if ! [[ "$CONTAINER_RAM_MB" =~ ^[0-9]+$ ]] || [ "$CONTAINER_RAM_MB" -lt 512 ] || [ "$CONTAINER_RAM_MB" -gt "$AVAILABLE_RAM_MB" ]; then
  echo "ARKANA_BUILD_RAM_MB must be at least 512 and no larger than available RAM ($AVAILABLE_RAM_MB MiB)." >&2
  exit 1
fi
DEFAULT_SWAP_MB=$(( AVAILABLE_SWAP_MB / 2 ))
if [ "$DEFAULT_SWAP_MB" -gt 2048 ]; then
  DEFAULT_SWAP_MB=2048
fi
CONTAINER_SWAP_MB=${ARKANA_BUILD_SWAP_MB:-$DEFAULT_SWAP_MB}
if ! [[ "$CONTAINER_SWAP_MB" =~ ^[0-9]+$ ]] || [ "$CONTAINER_SWAP_MB" -gt "$AVAILABLE_SWAP_MB" ]; then
  echo "ARKANA_BUILD_SWAP_MB must be a non-negative integer no larger than free swap ($AVAILABLE_SWAP_MB MiB)." >&2
  exit 1
fi

TOTAL_MEM_SWAP_MB=$(( CONTAINER_RAM_MB + CONTAINER_SWAP_MB ))

echo "Will use $CONTAINER_RAM_MB MiB of memory, $CONTAINER_SWAP_MB MiB of swap ($TOTAL_MEM_SWAP_MB MiB total limit), and $CPUS CPUs to build arkanaOS."
echo "Starting ISO build. This will take several hours."
docker build --cpu-quota="$((CPUS * 100000))" \
  --memory="${CONTAINER_RAM_MB}m" \
  --memory-swap="${TOTAL_MEM_SWAP_MB}m" \
  -t arkana-builder .
docker run --rm -it --init \
  --cap-add=MKNOD \
  -v "$SCRIPT_DIR:/build/arkana" \
  -v "$SCRIPT_DIR/.git:/build/arkana/.git:ro" \
  -e HOST_UID="$(id -u)" \
  -e HOST_GID="$(id -g)" \
  -e ARKANA_BUILD_NUMBER \
  -e ARKANA_RELEASE_PREFIX="$ARKANA_RELEASE_PREFIX" \
  -e THREADS="$CPUS" \
  -e NINJAJOBS="$CPUS" \
  --memory="${CONTAINER_RAM_MB}m" \
  --memory-swap="${TOTAL_MEM_SWAP_MB}m" \
  --cpus="$CPUS" \
  arkana-builder

if [[ "$MODE" == both ]]; then
  TARGET_ROOT="$SCRIPT_DIR/output/iso-root"
  if [[ ! -s "$SCRIPT_DIR/output/arkana.iso" || ! -f "$TARGET_ROOT/.arkana-iso-root" ]]; then
    echo "The ISO build completed without its ISO or validated root tree; refusing to build an update." >&2
    exit 1
  fi
  if [[ "$(<"$TARGET_ROOT/.arkana-iso-root")" != "arkanaOS ISO root" ]]; then
    echo "The generated update target does not have a valid arkanaOS ISO root marker." >&2
    exit 1
  fi
  echo "ISO build complete. Building the signed update package from output/iso-root."
  "$SCRIPT_DIR/build-update.sh" "${UPDATE_ARGS[@]}" --target-root "$TARGET_ROOT"
else
  echo "ISO build complete. Check ./output/arkana.iso."
fi
